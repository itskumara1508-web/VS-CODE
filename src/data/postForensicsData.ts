import { Platform } from '../types';

export type ForensicsDeviceCategory =
  | 'Mobile (iOS)'
  | 'Mobile (Android)'
  | 'Desktop (Windows)'
  | 'Desktop (macOS)'
  | 'Server / Bot API'
  | 'Tablet';

export type ForensicsThreatLevel = 'Low' | 'Medium' | 'High' | 'Critical';

export interface PostForensicsRecord {
  id: string;
  userId: string;
  userName: string;
  userAvatar: string;
  isVerified: boolean;
  userLocation: string; // e.g., "Bengaluru, Karnataka"
  country: string; // e.g., "India"
  countryCode: string; // "IN"
  countryFlag: string; // "🇮🇳"
  geoRegion: string; // e.g. "South Asia", "North America", "Europe"
  coordinates: [number, number]; // [lat, lng]
  ipAddress: string;
  isp: string;
  carrier: string; // e.g. "Jio 5G SA", "Airtel Fiber", "Singtel"
  batteryLevel: string; // e.g. "78%"
  deviceTimezone: string; // e.g. "UTC+05:30"
  isTimezoneSpoofed: boolean;
  timezoneAnalysis?: string;
  isVpnOrProxy: boolean;
  botSwarmId?: string; // e.g. "SWARM-CIB-01"
  postTime: string; // e.g. "2026-09-08 21:52:10 UTC"
  postTimeLocal: string; // e.g. "2026-09-09 03:22:10 IST"
  relativeTime: string; // e.g. "8 mins ago"
  hourOfDay: number; // 0-23
  platform: Platform | 'TikTok';
  device: string; // e.g., "Apple iPhone 15 Pro Max"
  deviceCategory: ForensicsDeviceCategory;
  clientApp: string; // e.g., "Twitter for iOS v10.42.1"
  userAgent: string;
  postContent: string;
  postUrl: string;
  threatLevel: ForensicsThreatLevel;
  sentiment: 'Supportive' | 'Against' | 'Anxiety' | 'Neutral' | 'Excitement' | 'Sarcasm';
  engagement: {
    views: number;
    likes: number;
    shares: number;
    comments: number;
  };
}

